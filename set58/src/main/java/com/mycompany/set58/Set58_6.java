     public static void main(String args[])
    {
       int a=5;
   
       System.out.println("Value of A is"+a++);
       System.out.println("Value of A is "+a); 
       
       System.out.println("value of a "+ ++a);
       System.out.println("Value of A"+a);
        
       System.out.println("Value of A is"+a--);
       System.out.println("Value of A is "+a); 
       
       System.out.println("value of a "+ --a);
       System.out.println("Value of A"+a);
        
        
    }
    
